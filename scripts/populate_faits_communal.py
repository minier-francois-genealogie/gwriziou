def _evt(
    *,
    categorie: str,
    debut: str,
    fin: str,
    libelle: str,
    description: str,
    commune: str,
    departement: str | None,
    region: str | None,
) -> dict:
    return {
        "type": "COMMUNAL",
        "categorie": categorie,
        "debut": debut,
        "fin": fin,
        "libelle": libelle,
        "description": description,
        "commune": commune,
        "departement": departement,
        "region": region,
    }



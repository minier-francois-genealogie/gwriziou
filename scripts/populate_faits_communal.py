TACOT_SLUGS = {
    "pluherlin", "rochefort_en_terre", "limerzel", "malansac", "peillac",
    "saint_grave", "saint_jacut_les_pins", "campeneac", "augan",
}


def build_events(meta: dict) -> list[dict]:
    slug = meta["slug"]
    if slug in CUSTOM:
        events = list(CUSTOM[slug])
    else:
        events = base_events(meta)

    if slug in TACOT_SLUGS and slug not in CUSTOM:
        events.append(
            _evt(
                categorie="SCIENCE",
                debut="1882",
                fin="1950",
                libelle="Desserte par le Tacot du Morbihan",
                description="Ligne à voie étroite du réseau morbihannais.",
                commune=meta["commune"],
                departement=meta.get("departement"),
                region=meta.get("region"),
            )
        )

    events.sort(key=lambda e: (e["debut"], e["fin"], e["libelle"]))
    return events


def main() -> None:
    index_path = COMMUNAL_DIR / "_index.json"
    if not index_path.is_file():
        raise SystemExit(f"Index introuvable : {index_path}")

    communes = json.loads(index_path.read_text(encoding="utf-8"))
    for meta in communes:
        slug = meta["slug"]
        path = COMMUNAL_DIR / f"{slug}.json"
        events = build_events(meta)
        path.write_text(
            json.dumps(events, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

    print(f"{len(communes)} fichiers communal alimentés dans {COMMUNAL_DIR}")


if __name__ == "__main__":
    main()
